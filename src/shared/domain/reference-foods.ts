export const referenceEquivalents: Equivalent[] = REFERENCE.map(([food, type, qty, ndb, kcal, protein, carbs, fat, aliases]) => ({
  id: `reference.${slug(food)}`,
  type,
  food,
  qty,
  unit: ndb === 'label-sanissimo' ? 'pza' : 'g',
  aliases: [...aliases],
  note: ndb === 'label-sanissimo'
    ? 'Estimado: 1 tostada de 12g, 8.3g de carbohidratos; depende de la marca y tamaño.'
    : `USDA SR Legacy NDB ${ndb} (por 100g: ${kcal}kcal, P ${protein}g, CHO ${carbs}g, grasa ${fat}g). Equivalencia estimada, no prescrita por tu nutriólogo.`,
  source: 'reference',
  flag: null,
}));

const cache = new WeakMap<PlanData, Equivalent[]>();
/** Personal plan takes precedence; references are available without editing/syncing the plan. */
export function catalogEquivalents(plan: PlanData): Equivalent[] {
  let result = cache.get(plan);
  if (result) return result;
  const names = new Set(plan.equivalents.map(e => norm(e.food)));
  result = [...plan.equivalents, ...referenceEquivalents.filter(e => !names.has(norm(e.food)))];
  cache.set(plan, result);
  return result;
}
